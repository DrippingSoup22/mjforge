bool measureSettleSizing(const Document& doc, WarpSizing* out, double seconds) {
  ExportMap map;
  CompileResult cr = compileMjcf(writeMjcf(doc, {}, &map));
  if (!cr.ok) return false;
  Simulator probe;
  if (!probe.start(cr.model, map)) return false;
  int steps = int(seconds / probe.model()->opt.timestep);
  for (int i = 0; i < steps && !probe.diverged(); ++i) probe.stepOnce();
  *out = probe.sizing();
  return true;
}

std::string mjwarpLoaderScript(const Document& doc, const std::string& xmlFile, const WarpSizing* measured) {
  WarpSizing ws;
  const char* source = "unknown (the model did not compile)";
  if (measured && measured->peakContacts + measured->peakBroadphase > 0) {
    ws = *measured;
    source = "measured in the MJForge simulation preview";
  } else if (measureSettleSizing(doc, &ws)) {
    // The start pose alone can miss contacts that only appear after landing.
    source = "measured while the model settled for 1.5 s (simulate in MJForge for motion peaks)";
  }
  char buf[2048];
  std::snprintf(buf, sizeof buf,
                "#!/usr/bin/env python3\n"
                "\"\"\"Loads %s in MuJoCo Warp and runs a few steps. Generated by MJForge " MJFORGE_VERSION ".\n\n"
                "Buffer sizes %s: %d contacts, %d broadphase candidate pairs, %d constraint\n"
                "rows per world. Raise them if MJWarp reports an overflow (e.g. rougher terrain, more robots).\n"
                "\"\"\"\n"
                "import os\n\n"
                "import mujoco\n"
                "import mujoco_warp as mjw\n"
                "import warp as wp\n\n"
                "XML = os.path.join(os.path.dirname(os.path.abspath(__file__)), \"%s\")\n"
                "NWORLD = 1024\n"
                "NCONMAX = %d  # contacts per world (must also cover MJWarp's broadphase pairs)\n"
                "NJMAX = %d  # constraint rows per world\n\n"
                "mjm = mujoco.MjModel.from_xml_path(XML)\n"
                "mjd = mujoco.MjData(mjm)\n"
                "if mjm.nkey > 0:\n"
                "  mujoco.mj_resetDataKeyframe(mjm, mjd, 0)  # start pose\n"
                "mujoco.mj_forward(mjm, mjd)\n\n"
                "m = mjw.put_model(mjm)\n"
                "d = mjw.put_data(mjm, mjd, nworld=NWORLD, nconmax=NCONMAX, njmax=NJMAX)\n\n"
                "for _ in range(100):\n"
                "  mjw.step(m, d)\n"
                "wp.synchronize()\n"
                "print(f\"stepped {NWORLD} worlds of {mjm.nq} qpos / {mjm.nu} actuators\")\n",
                xmlFile.c_str(), source, ws.peakContacts, ws.peakBroadphase, ws.peakConstraints, xmlFile.c_str(),
                ws.recommendedNconmax(), ws.recommendedNjmax());
  return buf;
}

